// Measures how well on-device Gemini Nano chooses clauses, in real Chrome through the real UI.
// Each task is asked, the chosen passages are read from the inspector, then the request is denied
// (nothing is sent to the cloud). Writes docs/EVAL-NANO.md.
//   node scripts/eval-nano.mjs [repeats]
import fs from "node:fs";
import { connect } from "./cdp.mjs";

const REPEATS = Number(process.argv[2] ?? 2);
const TASKS = [
  { task: "Is the non-compete and non-solicitation wording reasonable, and what would I ask to change?", needed: ["non-compete", "non-solicitation"] },
  { task: "Summarize what happens to me if the Company ends my employment, including notice, equity and any repayment.", needed: ["notice period", "equity", "relocation", "probation"] },
  { task: "How much will I be paid and what bonus can I expect?", needed: ["salary"] },
  { task: "What is my notice period and can the Company put me on garden leave?", needed: ["notice period"] },
  { task: "Who owns inventions I create, and is there any limit on that?", needed: ["intellectual property"] },
];

const page = await connect("http://127.0.0.1:5173/");
await page.send("Page.bringToFront");
await page.send("Page.navigate", { url: "http://127.0.0.1:5173/" }); // the first tab under the origin may be another page
await new Promise((r) => setTimeout(r, 2500));
// First click anywhere initializes and warms the model (a user gesture), as a real user's click would.
await page.evalJs("document.body.dispatchEvent(new PointerEvent('pointerdown', {bubbles:true}))");
await new Promise((r) => setTimeout(r, 15000));

// The console's request panel (data-testid=drawer) holds the gate and the chosen passages.
const text = () => page.evalJs("document.querySelector('[data-testid=\"drawer\"]')?.innerText ?? ''");
const has = (t, s) => t.toLowerCase().includes(s.toLowerCase());
async function waitFor(pred, ms = 240000) {
  const t0 = Date.now();
  while (Date.now() - t0 < ms) {
    const t = await text();
    if (pred(t)) return t;
    await new Promise((r) => setTimeout(r, 1000));
  }
  return await text();
}

const rows = [];
for (const t of TASKS) {
  for (let run = 1; run <= REPEATS; run++) {
    await page.evalJs(`(() => {
      const el = document.querySelector('textarea[aria-label="Task"]');
      Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype, 'value').set.call(el, ${JSON.stringify(t.task)});
      el.dispatchEvent(new Event('input', { bubbles: true }));
    })()`);
    await new Promise((r) => setTimeout(r, 300));
    await page.evalJs("[...document.querySelectorAll('button')].find(x=>x.textContent.includes('Ask Gemini'))?.click()");
    const seen = await waitFor((s) => has(s, "Awaiting your approval") || has(s, "could not run") || has(s, "Blocked"));
    const picked = await page.evalJs("[...document.querySelectorAll('[data-testid=\"clauses\"] .ac-clause-on')].map(r => r.innerText.replace(/\\s+/g,' '))");
    const total = await page.evalJs("document.querySelectorAll('[data-testid=\"clauses\"] .ac-clause').length");
    const ms = Number((/(\d+)\s*ms,\s*\d+\s*call/i.exec(await page.evalJs("document.querySelector('[data-testid=\"clauses\"]')?.parentElement?.innerText ?? ''")) ?? [])[1] ?? NaN);
    const ok = has(seen, "Awaiting your approval");
    const hit = t.needed.filter((n) => picked.some((p) => has(p, n)));
    const relevant = picked.filter((p) => t.needed.some((n) => has(p, n)));
    rows.push({
      task: t.task,
      run,
      ok,
      picked: picked.length,
      total,
      recall: hit.length / t.needed.length,
      precision: picked.length ? relevant.length / picked.length : 0,
      ms,
      missed: t.needed.filter((n) => !hit.includes(n)),
    });
    console.log(`${ok ? "ok " : "ERR"} run ${run}: ${picked.length}/${total} chosen, recall ${(100 * hit.length / t.needed.length).toFixed(0)}%, ${ms} ms  | ${t.task.slice(0, 50)}`);
    await page.evalJs("document.querySelector('[data-testid=\"drawer-deny\"]')?.click()");
    await new Promise((r) => setTimeout(r, 1200));
  }
}
page.close();

const good = rows.filter((r) => r.ok);
const avg = (xs) => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : 0);
const pct = (x) => `${(100 * x).toFixed(0)}%`;
const lat = good.map((r) => r.ms).filter(Number.isFinite).sort((a, b) => a - b);
const out = [];
out.push("# Nano clause-selection evaluation", "");
out.push("Measured in real desktop Chrome (D: profile, Gemini Nano on-device through Firebase AI Logic `ONLY_ON_DEVICE`) using the sample contract (16 clauses). Each task was asked through the real UI and the request was then denied, so nothing was sent to the cloud. Generated by `node scripts/eval-nano.mjs`.", "");
out.push("| Metric | Result |", "|---|---|");
out.push(`| Runs | ${rows.length} (${good.length} completed, ${rows.length - good.length} failed) |`);
out.push(`| Average recall of needed clauses | ${pct(avg(good.map((r) => r.recall)))} |`);
out.push(`| Average precision | ${pct(avg(good.map((r) => r.precision)))} |`);
out.push(`| Average clauses kept | ${avg(good.map((r) => r.picked)).toFixed(1)} of ${good[0]?.total ?? "?"} |`);
out.push(`| On-device latency | median ${lat[Math.floor(lat.length / 2)] ?? "n/a"} ms, max ${lat[lat.length - 1] ?? "n/a"} ms |`, "");
out.push("## Runs", "", "| Task | Run | Kept | Recall | Precision | Latency | Needed clause missed |", "|---|---|---|---|---|---|---|");
for (const r of rows) out.push(`| ${r.task.slice(0, 70)}${r.task.length > 70 ? "…" : ""} | ${r.run} | ${r.ok ? `${r.picked} of ${r.total}` : "failed"} | ${r.ok ? pct(r.recall) : "-"} | ${r.ok ? pct(r.precision) : "-"} | ${Number.isFinite(r.ms) ? r.ms + " ms" : "-"} | ${r.missed.join(", ") || "-"} |`);
out.push("", "## Reading these numbers", "", "- Recall is the share of clauses a careful reader needs that the model kept. A miss means the cloud answer may lack a passage it needed.", "- Precision is the share of kept clauses that were needed. Lower precision means more of the document was disclosed than necessary, but the policy engine still masks sensitive values in every kept clause.", "- Nano is not deterministic, so repeated runs can differ. Selection is only a proposal: code decides what may leave.", "- The first call after a page load includes model warm-up time.", "");
fs.mkdirSync("docs", { recursive: true });
fs.writeFileSync("docs/EVAL-NANO.md", out.join("\n"));
console.log(`\nrecall ${pct(avg(good.map((r) => r.recall)))}, precision ${pct(avg(good.map((r) => r.precision)))}, wrote docs/EVAL-NANO.md`);
